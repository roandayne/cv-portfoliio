/**
 * Vendors the handful of brand marks the hero shows into src/data/techMarks.js.
 *
 * simple-icons carries several thousand icons; only these nine are used, so
 * their path data is extracted at author time rather than shipped as a runtime
 * dependency and left to tree shaking. Re-run after changing the list:
 *
 *   node scripts/make-tech-marks.mjs
 *
 * Paths are CC0. Every name here appears in technicalFocus in src/data/site.js.
 */

import { writeFileSync } from 'node:fs';
import * as icons from 'simple-icons';

const WANTED = [
  'siReact',
  'siTypescript',
  'siVuedotjs',
  'siGo',
  'siPython',
  'siRubyonrails',
  'siLaravel',
  'siPostgresql',
  'siThreedotjs',
];

const marks = WANTED.map((key) => {
  const icon = icons[key];
  if (!icon) throw new Error(`simple-icons has no ${key}`);
  return { title: icon.title, path: icon.path };
});

const file = `/**
 * Brand marks for the hero, generated by scripts/make-tech-marks.mjs.
 * Do not edit by hand — change the list in that script and re-run it.
 *
 * Source: simple-icons (CC0). Every path is drawn on a 24x24 grid.
 */

export const techMarks = ${JSON.stringify(marks, null, 2)};
`;

writeFileSync(new URL('../src/data/techMarks.js', import.meta.url), file);
console.log(`wrote ${marks.length} marks`);
